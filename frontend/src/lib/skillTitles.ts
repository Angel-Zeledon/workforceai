const KEEP_UPPER = new Set(["b2b", "b2c", "api", "sql", "seo", "nps", "kpi", "okr", "hr", "it", "sop", "faq", "nda", "ab", "ad", "ui", "ux", "roi"]);

/** "b2b-proposal" -> "B2B proposal": the id as a sentence, for skills that have no written title. */
export function humanizeSkillId(id: string): string {
  const words = id.split(/[-_\s]+/).filter(Boolean).map((w, i) => (KEEP_UPPER.has(w.toLowerCase()) ? w.toUpperCase() : i === 0 ? w[0].toUpperCase() + w.slice(1) : w));
  return words.join(" ");
}

/** The title of a skill to show people: the starter's written title in their language, else the id as a sentence. */
export function skillTitle(name: string, locale: string): string {
  return (locale.startsWith("en") ? EN : ES)[name] ?? humanizeSkillId(name);
}

/** Relative age in words ("hace un momento", "hace 3 días", "3 days ago"). */
export function relativeAge(iso: string, locale: string, now = Date.now()): string {
  const t = new Date(iso).getTime();
  if (isNaN(t)) return "";
  const s = Math.max(0, Math.round((now - t) / 1000));
  const en = locale.startsWith("en"), pt = locale.startsWith("pt");
  const w = (n: number, es: [string, string], enw: [string, string], ptw: [string, string]) => {
    const pick = en ? enw : pt ? ptw : es;
    const unit = n === 1 ? pick[0] : pick[1];
    return en ? `${n} ${unit} ago` : pt ? `há ${n} ${unit}` : `hace ${n} ${unit}`;
  };
  if (s < 60) return en ? "just now" : pt ? "agora mesmo" : "hace un momento";
  const m = Math.floor(s / 60);
  if (m < 60) return w(m, ["minuto", "minutos"], ["minute", "minutes"], ["minuto", "minutos"]);
  const h = Math.floor(m / 60);
  if (h < 24) return w(h, ["hora", "horas"], ["hour", "hours"], ["hora", "horas"]);
  const d = Math.floor(h / 24);
  if (d < 30) return w(d, ["día", "días"], ["day", "days"], ["dia", "dias"]);
  const mo = Math.floor(d / 30);
  if (mo < 12) return w(mo, ["mes", "meses"], ["month", "months"], ["mês", "meses"]);
  const y = Math.floor(mo / 12);
  return w(y, ["año", "años"], ["year", "years"], ["ano", "anos"]);
}
